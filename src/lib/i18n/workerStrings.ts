const DICTS: Record<WorkerLocale, Dict> = { ko: KO, en: EN, zh: ZH, ja: JA };

export type WorkerStringKey = keyof Dict;

export function workerT(locale: WorkerLocale, key: WorkerStringKey): string {
  return DICTS[locale]?.[key] || KO[key];
}

export function roleLabelForLocale(role: string, locale: WorkerLocale): string {
  switch (role) {
    case "master":
      return workerT(locale, "roleMaster");
    case "project_admin":
      return workerT(locale, "rolePa");
    case "safety_manager":
      return workerT(locale, "roleSm");
    case "site_manager":
      return workerT(locale, "roleSiteMgr");
    case "supervisor":
      return workerT(locale, "roleSupervisor");
    case "site_supervisor":
      return workerT(locale, "roleSiteSupervisor");
    case "worker":
    case "contractor":
      return workerT(locale, "roleWorker");
    default:
      return workerT(locale, "roleUser");
  }
}